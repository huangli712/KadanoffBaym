#!/usr/bin/env python3
# Regenerate the module index (appendix D) and the module size table
# (chapter 13) directly from the sources under src/, so the numbers in
# the book cannot drift from the tree.
#
# Usage: python3 docs/scripts/gen_modules.py
# Files are rewritten only when the generated content differs.

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src"

# directory groups in the order used by the appendix
GROUPS = [
    "linalg", "math", "types", "base", "storage", "algebra", "variants",
    "weights", "convolution", "dyson", "vie2", "equilibrium", "fourier",
    "observables", "io",
]

def line_count(path: Path) -> int:
    with path.open("rb") as fh:
        return sum(1 for _ in fh)

def group_files(group: str) -> list[Path]:
    files = sorted((SRC / group).glob("*.rs"), key=lambda p: (p.name == "mod.rs", p.name))
    return files

def root_files() -> list[Path]:
    files = sorted(p for p in SRC.glob("*.rs"))
    return files

def fmt_rows(rows: list[tuple[str, int]]) -> str:
    return "\n".join(f"    \\code{{{name}}} & {n} \\\\" for name, n in rows)

def gen_appendix() -> str:
    parts = []
    parts.append(r"""% ---------------------------------------------------------------------
%  附录 D 模块与文件索引
%
%  THIS FILE IS GENERATED by docs/scripts/gen_modules.py -- edit the
%  script, not this file.
% ---------------------------------------------------------------------
\chapter{模块与文件索引}
\label{app:modules}

\begin{longtable}{@{}p{0.42\textwidth}r@{}}
    \caption[源文件与行数]{源文件与行数}\label{tab:file-index}\\
    \toprule
    文件 & 行数 \\
    \midrule
    \endfirsthead
    \toprule
    文件 & 行数 \\
    \midrule
    \endhead
    \bottomrule
    \endfoot""")
    parts.append("    \\multicolumn{2}{@{}l}{\\textbf{\\code{src/}}} \\\\")
    parts.append(fmt_rows([(p.name, line_count(p)) for p in root_files()]))
    for group in GROUPS:
        parts.append("    \\addlinespace")
        parts.append(f"    \\multicolumn{{2}}{{@{{}}l}}{{\\textbf{{\\code{{src/{group}}}}}}} \\\\")
        parts.append(fmt_rows([(p.name, line_count(p)) for p in group_files(group)]))
    parts.append(r"\end{longtable}")
    return "\n".join(parts) + "\n"

PUB_FN = re.compile(r"^\s*pub (?:const )?fn ", re.M)

def module_stats():
    rows = []
    single = {"complex": "complex.rs"}
    for group in list(single) + GROUPS:
        if group in single:
            files = [SRC / single[group]]
        else:
            files = group_files(group)
        lines = sum(line_count(p) for p in files)
        pubfns = sum(len(PUB_FN.findall(p.read_text())) for p in files)
        rows.append((group, len(files), lines, pubfns))
    lib = SRC / "lib.rs"
    rows.append(("lib.rs", 1, line_count(lib), len(PUB_FN.findall(lib.read_text()))))
    return rows

def gen_size_rows() -> str:
    stats = module_stats()
    order = ["complex", "linalg", "math", "types", "base", "storage",
             "algebra", "variants", "weights", "convolution", "dyson", "vie2", "equilibrium",
             "fourier", "observables", "io", "lib.rs"]
    by_name = {name: s for name, *s in stats}
    lines_out = []
    width = max(len(str(s[2])) for s in stats)
    for name in order:
        files, lines, pubfns = by_name[name]
        lines_out.append(
            f"        \\code{{{name}}} & {files} & {lines:{width}} & {pubfns} \\\\"
        )
    tot_files = sum(s[1] for s in stats)
    tot_lines = sum(s[2] for s in stats)
    tot_pub = sum(s[3] for s in stats)
    lines_out.append("        \\midrule")
    lines_out.append(
        f"        合计 & {tot_files} & {tot_lines:,} & {tot_pub} \\\\".replace(",", "\\,")
    )
    return "\n".join(lines_out)

BEGIN = "% BEGIN GENERATED SIZE TABLE (gen_modules.py)"
END = "% END GENERATED SIZE TABLE (gen_modules.py)"

def write_if_changed(path: Path, content: str) -> bool:
    if path.exists() and path.read_text() == content:
        return False
    path.write_text(content)
    return True

def main() -> int:
    appd = ROOT / "docs/appendices/appD-modules.tex"
    changed = write_if_changed(appd, gen_appendix())
    print(f"appD-modules.tex: {'rewritten' if changed else 'up to date'}")

    ch13 = ROOT / "docs/chapters/ch13-engineering.tex"
    text = ch13.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        print("ch13-engineering.tex: generated markers not found", file=sys.stderr)
        return 1
    block = BEGIN + "\n" + gen_size_rows() + "\n" + END
    new_text = pattern.sub(lambda _m: block, text, count=1)
    changed = write_if_changed(ch13, new_text)
    print(f"ch13-engineering.tex: {'rewritten' if changed else 'up to date'}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
